(function tierAchievements() {
  const fixed = {
    bridges: [2, 4],
    wonders: [2, 3],
    collections: [2, 4],
    level: null,
  };
  const base = ACHIEVEMENTS.slice();
  for (const a of base) {
    a.tier = 1;
    if (a.stat === "level") {
      if (a.goal === 5)
        ACHIEVEMENTS.push(
          Object.assign({}, a, {
            id: a.id + "_s",
            name: a.name + " II",
            desc: "Reach level 25",
            goal: 25,
            reward: a.reward * 3,
            tier: 2,
          }),
          Object.assign({}, a, {
            id: a.id + "_g",
            name: a.name + " III",
            desc: "Reach level 50",
            goal: 50,
            reward: a.reward * 8,
            tier: 3,
          }),
        );
      else
        ACHIEVEMENTS.push(
          Object.assign({}, a, {
            id: a.id + "_s",
            name: a.name + " II",
            desc: "Reach level 75",
            goal: 75,
            reward: a.reward * 3,
            tier: 2,
          }),
          Object.assign({}, a, {
            id: a.id + "_g",
            name: a.name + " III",
            desc: "Reach level 100",
            goal: 100,
            reward: a.reward * 8,
            tier: 3,
          }),
        );
      continue;
    }
    let g2, g3;
    if (fixed[a.stat]) [g2, g3] = fixed[a.stat];
    else if (a.stat === "pop") {
      g2 = a.goal * 3;
      g3 = a.goal * 10;
    } else {
      g2 = a.goal * 5;
      g3 = a.goal * 20;
    }
    if (g2 <= a.goal) continue;
    const rx = (g) => a.desc.replace(/[\d,]+/, g.toLocaleString("en-US"));
    ACHIEVEMENTS.push(
      Object.assign({}, a, {
        id: a.id + "_s",
        name: a.name + " II",
        desc: rx(g2),
        goal: g2,
        reward: a.reward * 3,
        tier: 2,
      }),
    );
    ACHIEVEMENTS.push(
      Object.assign({}, a, {
        id: a.id + "_g",
        name: a.name + " III",
        desc: rx(g3),
        goal: g3,
        reward: a.reward * 8,
        tier: 3,
      }),
    );
  }
})();

