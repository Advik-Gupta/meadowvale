function jobSpec(t) {
  if (JOBS[t]) return JOBS[t];
  const b = BUILD[t];
  if (!b) return null;
  if (b.biz) return b.biz.job;
  if (b.cat === "prod")
    return {
      n: 3 + Math.round((b.w * b.h) / 2),
      k: FOOD_SHOPS.has(t) ? "chef" : "worker",
      w: 38,
    };
  if (b.cat === "ind") return { n: 6, k: "worker", w: 48 };
  if (b.animal || b.orchard || t === "greenhouse")
    return { n: 2, k: "farmer", w: 30 };
  return null;
}

